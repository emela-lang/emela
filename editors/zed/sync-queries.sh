#!/bin/sh
# Writes languages/emela/highlights.scm from the Neovim-flavored queries in
# editors/tree-sitter-emela/queries, renaming the captures that Zed's themes do not know.
# With --check, fails instead if the copy is out of date.
set -eu
here=$(cd "$(dirname "$0")" && pwd)
source="$here/../tree-sitter-emela/queries/highlights.scm"
target="$here/languages/emela/highlights.scm"

generate() {
  echo "; Generated by editors/zed/sync-queries.sh from editors/tree-sitter-emela/queries."
  echo "; Edit that file and run the script again."
  sed -e '1,2d' \
      -e 's/@comment\.documentation/@comment.doc/g' \
      -e 's/@variable\.member/@property/g' \
      -e 's/@variable\.builtin/@variable.special/g' \
      -e 's/@module/@type/g' \
      -e 's/ @spell//g' \
      "$source"
}

if [ "${1:-}" = --check ]; then
  generate | cmp -s - "$target" || { echo "$target is out of date; run $0" >&2; exit 1; }
else
  generate > "$target"
fi
