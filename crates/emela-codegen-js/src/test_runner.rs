//! The test entry module (spec chapter 13).
//!
//! Imports the emitted module, calls test functions one by one, and writes the results to stdout.
//!
//! The result lines are a private protocol between the entry module and `emela test`, which runs
//! the entry module on node and reads its stdout. They are not in the spec; what users see is
//! `[cmd.test.output]` and `[cmd.test.outcome]`.
//!
//! - One event per line: U+001E, `emela-test`, one space, a JSON value, a newline. The leading
//!   U+001E sets the line apart from whatever the test functions print.
//! - `{"event":"result","name":…,"outcome":…,"message":…}` per test. `name` is the test name of
//!   `[test.command]`. `outcome` is `"ok"` (no message), `"error"` (an unhandled error; the message
//!   is the error's display, `NotFound(id: 0)`), `"defect"` (the defect's message) or
//!   `"interrupted"` (unwound while suspended; no message).
//! - `{"event":"done"}` last.
//!
//! Tests run one at a time; the next starts after the previous one ended, and an error, defect or
//! interruption does not stop the others.

use std::fmt::Write as _;

use crate::emit::js_string;

/// The test runner source (an ES module), embedded in the entry module.
pub const TEST_RUNNER: &str = include_str!("test_runner.mjs");

/// The prefix of the result lines the test runner writes to stdout, followed by JSON.
pub const TEST_EVENT_PREFIX: &str = "\u{1e}emela-test ";

#[derive(Debug, Clone, Copy)]
pub struct TestEntry<'a> {
    /// The name shown in results.
    pub name: &'a str,
    /// The name of the function `module` exports (its Emela name).
    pub export: &'a str,
}

/// An entry module that calls `tests` of `module` in order. `module` is relative to the entry
/// module (e.g. `./main.mjs`). Runs directly on node. Suspending test functions are driven by the
/// runtime's `$start`, which `module` exports.
pub fn emit_test_main(module: &str, tests: &[TestEntry]) -> String {
    let mut out = String::from("// Test entry module generated by Emela.\n");
    let _ = writeln!(out, "import * as $m from {};", js_string(module));
    out.push('\n');
    for line in TEST_RUNNER.lines() {
        out.push_str(line.strip_prefix("export ").unwrap_or(line));
        out.push('\n');
    }
    out.push_str("\nawait $runTests([\n");
    for t in tests {
        let _ = writeln!(
            out,
            "  [{}, $m[{}]],",
            js_string(t.name),
            js_string(t.export)
        );
    }
    out.push_str("], $m.$start);\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn prefix_matches_runner() {
        let escaped = TEST_EVENT_PREFIX.replace('\u{1e}', "\\x1e");
        assert!(TEST_RUNNER.contains(&format!("\"{escaped}\"")));
    }

    #[test]
    fn main_imports_module_and_lists_tests() {
        let js = emit_test_main(
            "./main.mjs",
            &[
                TestEntry {
                    name: "adds",
                    export: "adds",
                },
                TestEntry {
                    name: "Util.new",
                    export: "new",
                },
            ],
        );
        assert!(js.contains("import * as $m from \"./main.mjs\";\n"));
        assert!(js.contains("  [\"adds\", $m[\"adds\"]],\n  [\"Util.new\", $m[\"new\"]],\n"));
        assert!(!js.contains("export async"));
    }
}
