/// The route function of a kind of peripheral: `static int em_<kind>_route(<Id> id, bool setup)`
/// gives the index of the peripheral's handle in `em_<kind>`, with (when `setup`) its clocks on,
/// its pins set to their alternate function and the handle's instance set; -1 for none.
fn route_function(
    w: &mut Writer,
    board: &BoardDef,
    kind: &str,
    id_type: &str,
    handle: &str,
    routes: &[Route],
    pin_mode: &dyn Fn(&str) -> (&'static str, &'static str),
) {
    let short = match kind {
        "uart" => "Uart",
        "i2c" => "I2c",
        _ => "Spi",
    };
    let peripheral =
        crate::board::split(&format!("Std.Embedded.{short}.{id_type}")).map(|(p, _)| p);
    w.line_raw(&format!(
        "static {handle} em_{kind}[{}];",
        routes.len().max(1)
    ));
    w.blank();
    w.line_raw(&format!(
        "static int em_{kind}_route(Emela{short}{} id, bool setup) {{",
        id_type.strip_prefix(short).unwrap_or(id_type)
    ));
    w.line_raw("  GPIO_InitTypeDef pin = {0};");
    w.line_raw("  switch (id) {");
    for (r, route) in routes.iter().enumerate() {
        let constant = peripheral
            .as_ref()
            .map(|p| p.constant(id_type, &route.id))
            .unwrap_or_default();
        w.line_raw(&format!("  case {constant}: /* {} */", route.instance));
        w.line_raw("    if (setup) {");
        w.line_raw(&format!("      __HAL_RCC_{}_CLK_ENABLE();", route.instance));
        for (role, id) in &route.pins {
            let Some(p) = board.pin(*id) else { continue };
            let (mode, pull) = pin_mode(role);
            w.line_raw(&format!(
                "      __HAL_RCC_GPIO{}_CLK_ENABLE(); /* {role}: {} {} */",
                p.port,
                p.label,
                p.mcu_name()
            ));
            w.line_raw(&format!(
                "      pin.Pin = GPIO_PIN_{}; pin.Mode = {mode}; pin.Pull = {pull}; \
                 pin.Speed = GPIO_SPEED_FREQ_VERY_HIGH; pin.Alternate = {}; HAL_GPIO_Init(GPIO{}, &pin);",
                p.pin, route.af, p.port
            ));
        }
        w.line_raw(&format!(
            "      em_{kind}[{r}].Instance = {};",
            route.instance
        ));
        w.line_raw("    }");
        w.line_raw(&format!("    return {r};"));
    }
    w.line_raw("  default:");
    w.line_raw("    (void)pin;");
    w.line_raw("    (void)setup;");
    w.line_raw("    return -1;");
    w.line_raw("  }");
    w.line_raw("}");
}

