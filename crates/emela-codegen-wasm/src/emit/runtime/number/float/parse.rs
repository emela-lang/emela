//! `Float.parse`: the binary64 nearest to a decimal text.

use super::*;

// ---- parse ----

pub(super) fn parse(b: &mut Builder, ins: &mut InstructionSink) {
    const EXPE: u32 = 3;
    const K: u32 = 4;
    const MANT: u32 = 5;
    const V: u32 = 6;
    const YBITS: u32 = 7;
    const N: u32 = 9;
    const I: u32 = 10;
    const NEG: u32 = 11;
    const SIG: u32 = 12;
    const FRAC: u32 = 13;
    const KEPT: u32 = 14;
    const CMP: u32 = 16;
    const PARITY: u32 = 17;
    const CNT: u32 = 18;
    const BYTE: u32 = 19;
    const DIG: u32 = 20;
    const M19: u32 = 21;
    const L: u32 = 22;
    const ESIGN: u32 = 23;
    const FLAG: u32 = 24;
    const J: u32 = 25;
    const IDIG: u32 = 26;
    const TRUNC: u32 = 27;
    const Y: u32 = 28;
    let din = area(b, AREA_IN);
    let meta = area(b, AREA_META);
    // The length, and `NaN` (which takes no sign).
    ins.local_get(0);
    ins.i32_load(mem(HDR, 4));
    ins.local_set(N);
    ins.i32_const(0);
    ins.local_set(I);
    ins.local_get(N);
    ins.i32_const(3);
    ins.i32_eq();
    ins.if_(BlockType::Empty);
    ins.i32_const(1);
    ins.local_set(FLAG);
    for (k, byte) in b"NaN".iter().enumerate() {
        ins.local_get(FLAG);
        src_byte_at(ins, 0, I, k as u32);
        ins.i32_const(*byte as i32);
        ins.i32_eq();
        ins.i32_and();
        ins.local_set(FLAG);
    }
    ins.local_get(FLAG);
    ins.if_(BlockType::Empty);
    ins.f64_const(f64::NAN.into());
    finish(b, ins, None);
    ins.end();
    ins.end();
    ins.local_get(N);
    ins.i32_eqz();
    ins.if_(BlockType::Empty);
    ins.local_get(2);
    ins.return_();
    ins.end();
    ins.i32_const(0);
    ins.local_set(I);
    ins.i32_const(0);
    ins.local_set(NEG);
    src_byte(ins, 0, I);
    ins.local_set(BYTE);
    ins.local_get(BYTE);
    ins.i32_const(b'+' as i32);
    ins.i32_eq();
    ins.local_get(BYTE);
    ins.i32_const(b'-' as i32);
    ins.i32_eq();
    ins.i32_or();
    ins.if_(BlockType::Empty);
    ins.local_get(BYTE);
    ins.i32_const(b'-' as i32);
    ins.i32_eq();
    ins.local_set(NEG);
    ins.i32_const(1);
    ins.local_set(I);
    ins.end();
    // `Infinity` after the sign.
    ins.local_get(N);
    ins.local_get(I);
    ins.i32_sub();
    ins.i32_const(8);
    ins.i32_eq();
    ins.if_(BlockType::Empty);
    ins.i32_const(1);
    ins.local_set(FLAG);
    for (k, byte) in b"Infinity".iter().enumerate() {
        ins.local_get(FLAG);
        src_byte_at(ins, 0, I, k as u32);
        ins.i32_const(*byte as i32);
        ins.i32_eq();
        ins.i32_and();
        ins.local_set(FLAG);
    }
    ins.local_get(FLAG);
    ins.if_(BlockType::Empty);
    ins.f64_const(f64::INFINITY.into());
    finish(b, ins, Some(NEG));
    ins.end();
    ins.end();
    // Integer digits.
    //
    // Only the first 800 significant digits are kept. A rounding midpoint is a dyadic rational
    // whose exact decimal has at most 768 significant digits, so a dropped digit can only matter
    // when the kept prefix already equals the midpoint. `TRUNC` remembers that a nonzero digit was
    // dropped, and the comparisons treat the input as strictly greater than the kept prefix.
    ins.i32_const(0);
    ins.local_set(SIG);
    ins.i32_const(0);
    ins.local_set(FRAC);
    ins.i32_const(0);
    ins.local_set(KEPT);
    ins.i32_const(0);
    ins.local_set(IDIG);
    ins.i32_const(0);
    ins.local_set(TRUNC);
    ins.block(BlockType::Empty);
    ins.loop_(BlockType::Empty);
    ins.local_get(I);
    ins.local_get(N);
    ins.i32_ge_u();
    ins.br_if(1);
    src_byte(ins, 0, I);
    ins.local_set(BYTE);
    ins.local_get(BYTE);
    ins.i32_const(b'0' as i32);
    ins.i32_lt_u();
    ins.local_get(BYTE);
    ins.i32_const(b'9' as i32);
    ins.i32_gt_u();
    ins.i32_or();
    ins.br_if(1);
    ins.local_get(BYTE);
    ins.i32_const(b'0' as i32);
    ins.i32_sub();
    ins.local_set(DIG);
    // Leading zeros are not part of the significant digits.
    ins.local_get(SIG);
    ins.i32_eqz();
    ins.local_get(DIG);
    ins.i32_eqz();
    ins.i32_and();
    ins.if_(BlockType::Empty);
    ins.else_();
    ins.local_get(KEPT);
    ins.i32_const(800);
    ins.i32_lt_u();
    ins.if_(BlockType::Empty);
    elem(ins, din, KEPT, 1);
    ins.local_get(BYTE);
    ins.i32_store8(mem(0, 1));
    bump(ins, KEPT);
    ins.else_();
    ins.local_get(DIG);
    ins.i32_const(0);
    ins.i32_ne();
    ins.if_(BlockType::Empty);
    ins.i32_const(1);
    ins.local_set(TRUNC);
    ins.end();
    ins.end();
    bump(ins, SIG);
    ins.end();
    bump(ins, IDIG);
    bump(ins, I);
    ins.br(0);
    ins.end();
    ins.end();
    ins.local_get(IDIG);
    ins.i32_eqz();
    ins.if_(BlockType::Empty);
    ins.local_get(2);
    ins.return_();
    ins.end();
    // The fraction (the dot needs at least one digit after it).
    ins.local_get(I);
    ins.local_get(N);
    ins.i32_lt_u();
    ins.if_(BlockType::Empty);
    src_byte(ins, 0, I);
    ins.i32_const(b'.' as i32);
    ins.i32_eq();
    ins.if_(BlockType::Empty);
    bump(ins, I);
    ins.i32_const(0);
    ins.local_set(FLAG);
    ins.block(BlockType::Empty);
    ins.loop_(BlockType::Empty);
    ins.local_get(I);
    ins.local_get(N);
    ins.i32_ge_u();
    ins.br_if(1);
    src_byte(ins, 0, I);
    ins.local_set(BYTE);
    ins.local_get(BYTE);
    ins.i32_const(b'0' as i32);
    ins.i32_lt_u();
    ins.local_get(BYTE);
    ins.i32_const(b'9' as i32);
    ins.i32_gt_u();
    ins.i32_or();
    ins.br_if(1);
    ins.local_get(BYTE);
    ins.i32_const(b'0' as i32);
    ins.i32_sub();
    ins.local_set(DIG);
    ins.local_get(SIG);
    ins.i32_eqz();
    ins.local_get(DIG);
    ins.i32_eqz();
    ins.i32_and();
    ins.if_(BlockType::Empty);
    ins.else_();
    ins.local_get(KEPT);
    ins.i32_const(800);
    ins.i32_lt_u();
    ins.if_(BlockType::Empty);
    elem(ins, din, KEPT, 1);
    ins.local_get(BYTE);
    ins.i32_store8(mem(0, 1));
    bump(ins, KEPT);
    ins.else_();
    ins.local_get(DIG);
    ins.i32_const(0);
    ins.i32_ne();
    ins.if_(BlockType::Empty);
    ins.i32_const(1);
    ins.local_set(TRUNC);
    ins.end();
    ins.end();
    bump(ins, SIG);
    ins.end();
    bump(ins, FRAC);
    bump(ins, FLAG);
    bump(ins, I);
    ins.br(0);
    ins.end();
    ins.end();
    ins.local_get(FLAG);
    ins.i32_eqz();
    ins.if_(BlockType::Empty);
    ins.local_get(2);
    ins.return_();
    ins.end();
    ins.end();
    ins.end();
    // The exponent.
    ins.i64_const(0);
    ins.local_set(EXPE);
    ins.local_get(I);
    ins.local_get(N);
    ins.i32_lt_u();
    ins.if_(BlockType::Empty);
    src_byte(ins, 0, I);
    ins.local_set(BYTE);
    ins.local_get(BYTE);
    ins.i32_const(b'e' as i32);
    ins.i32_eq();
    ins.local_get(BYTE);
    ins.i32_const(b'E' as i32);
    ins.i32_eq();
    ins.i32_or();
    ins.if_(BlockType::Empty);
    bump(ins, I);
    ins.i32_const(1);
    ins.local_set(ESIGN);
    ins.local_get(I);
    ins.local_get(N);
    ins.i32_lt_u();
    ins.if_(BlockType::Empty);
    src_byte(ins, 0, I);
    ins.local_set(BYTE);
    ins.local_get(BYTE);
    ins.i32_const(b'+' as i32);
    ins.i32_eq();
    ins.local_get(BYTE);
    ins.i32_const(b'-' as i32);
    ins.i32_eq();
    ins.i32_or();
    ins.if_(BlockType::Empty);
    ins.local_get(BYTE);
    ins.i32_const(b'-' as i32);
    ins.i32_eq();
    ins.if_(BlockType::Empty);
    ins.i32_const(-1);
    ins.local_set(ESIGN);
    ins.end();
    bump(ins, I);
    ins.end();
    ins.end();
    ins.local_get(I);
    ins.local_get(N);
    ins.i32_ge_u();
    ins.if_(BlockType::Empty);
    ins.local_get(2);
    ins.return_();
    ins.end();
    ins.i64_const(0);
    ins.local_set(V);
    ins.i32_const(0);
    ins.local_set(FLAG);
    ins.block(BlockType::Empty);
    ins.loop_(BlockType::Empty);
    ins.local_get(I);
    ins.local_get(N);
    ins.i32_ge_u();
    ins.br_if(1);
    src_byte(ins, 0, I);
    ins.local_set(BYTE);
    ins.local_get(BYTE);
    ins.i32_const(b'0' as i32);
    ins.i32_lt_u();
    ins.local_get(BYTE);
    ins.i32_const(b'9' as i32);
    ins.i32_gt_u();
    ins.i32_or();
    ins.br_if(1);
    // Saturate once the exponent is far beyond any digit count (a string is under 2^32
    // bytes), so `k` below stays exact without overflowing.
    ins.local_get(V);
    ins.i64_const(100_000_000_000_000_000);
    ins.i64_lt_s();
    ins.if_(BlockType::Empty);
    ins.local_get(V);
    ins.i64_const(10);
    ins.i64_mul();
    ins.local_get(BYTE);
    ins.i32_const(b'0' as i32);
    ins.i32_sub();
    ins.i64_extend_i32_u();
    ins.i64_add();
    ins.local_set(V);
    ins.end();
    bump(ins, FLAG);
    bump(ins, I);
    ins.br(0);
    ins.end();
    ins.end();
    ins.local_get(FLAG);
    ins.i32_eqz();
    ins.if_(BlockType::Empty);
    ins.local_get(2);
    ins.return_();
    ins.end();
    ins.local_get(ESIGN);
    ins.i32_const(0);
    ins.i32_lt_s();
    ins.if_(BlockType::Empty);
    ins.i64_const(0);
    ins.local_get(V);
    ins.i64_sub();
    ins.local_set(V);
    ins.end();
    ins.local_get(V);
    ins.local_set(EXPE);
    ins.end();
    ins.end();
    // The whole string must be consumed.
    ins.local_get(I);
    ins.local_get(N);
    ins.i32_ne();
    ins.if_(BlockType::Empty);
    ins.local_get(2);
    ins.return_();
    ins.end();
    // Zero (either sign).
    ins.local_get(SIG);
    ins.i32_eqz();
    ins.if_(BlockType::Empty);
    ins.f64_const(0.0.into());
    finish(b, ins, Some(NEG));
    ins.end();
    // `k` is the power of ten of the least significant kept digit.
    ins.local_get(SIG);
    ins.local_get(KEPT);
    ins.i32_sub();
    ins.i64_extend_i32_s();
    ins.local_get(EXPE);
    ins.i64_add();
    ins.local_get(FRAC);
    ins.i64_extend_i32_s();
    ins.i64_sub();
    ins.local_set(K);
    ins.local_get(KEPT);
    ins.local_set(L);
    // Out of range in either direction.
    ins.local_get(K);
    ins.i64_const(309);
    ins.i64_ge_s();
    ins.if_(BlockType::Empty);
    ins.f64_const(f64::INFINITY.into());
    finish(b, ins, Some(NEG));
    ins.end();
    ins.local_get(K);
    ins.local_get(L);
    ins.i64_extend_i32_s();
    ins.i64_add();
    ins.i64_const(-324);
    ins.i64_le_s();
    ins.if_(BlockType::Empty);
    ins.f64_const(0.0.into());
    finish(b, ins, Some(NEG));
    ins.end();
    // The naive value: the first 19 digits and their power of ten.
    ins.local_get(L);
    ins.i32_const(19);
    ins.i32_lt_s();
    ins.if_(BlockType::Result(ValType::I32));
    ins.local_get(L);
    ins.else_();
    ins.i32_const(19);
    ins.end();
    ins.local_set(M19);
    ins.i64_const(0);
    ins.local_set(MANT);
    ins.i32_const(0);
    ins.local_set(J);
    ins.block(BlockType::Empty);
    ins.loop_(BlockType::Empty);
    ins.local_get(J);
    ins.local_get(M19);
    ins.i32_ge_u();
    ins.br_if(1);
    ins.local_get(MANT);
    ins.i64_const(10);
    ins.i64_mul();
    load_u8(ins, din, J);
    ins.i32_const(b'0' as i32);
    ins.i32_sub();
    ins.i64_extend_i32_u();
    ins.i64_add();
    ins.local_set(MANT);
    bump(ins, J);
    ins.br(0);
    ins.end();
    ins.end();
    ins.local_get(MANT);
    ins.f64_convert_i64_u();
    ins.local_set(Y);
    ins.local_get(L);
    ins.local_get(M19);
    ins.i32_sub();
    ins.i64_extend_i32_s();
    ins.local_get(K);
    ins.i64_add();
    ins.local_set(YBITS);
    ins.local_get(YBITS);
    ins.i64_const(0);
    ins.i64_ge_s();
    ins.if_(BlockType::Empty);
    ins.local_get(Y);
    ins.local_get(YBITS);
    ins.i32_wrap_i64();
    ins.call(rt(b, "float_pow10"));
    ins.f64_mul();
    ins.local_set(Y);
    ins.else_();
    // Divide in chunks of at most 10^308, which is the largest power of ten a binary64 holds.
    ins.i64_const(0);
    ins.local_get(YBITS);
    ins.i64_sub();
    ins.i32_wrap_i64();
    ins.local_set(FLAG);
    ins.block(BlockType::Empty);
    ins.loop_(BlockType::Empty);
    ins.local_get(FLAG);
    ins.i32_eqz();
    ins.br_if(1);
    ins.local_get(FLAG);
    ins.i32_const(308);
    ins.i32_gt_s();
    ins.if_(BlockType::Result(ValType::I32));
    ins.i32_const(308);
    ins.else_();
    ins.local_get(FLAG);
    ins.end();
    ins.local_set(J);
    ins.local_get(Y);
    ins.local_get(J);
    ins.call(rt(b, "float_pow10"));
    ins.f64_div();
    ins.local_set(Y);
    ins.local_get(FLAG);
    ins.local_get(J);
    ins.i32_sub();
    ins.local_set(FLAG);
    ins.br(0);
    ins.end();
    ins.end();
    ins.end();
    // Move by single neighbours until the input is inside the rounding interval. The naive value
    // is within a few ulps, so this takes a handful of steps; the guard only stops a bug from
    // spinning forever.
    ins.i32_const(0);
    ins.local_set(CNT);
    ins.block(BlockType::Empty);
    ins.loop_(BlockType::Empty);
    bump(ins, CNT);
    ins.local_get(CNT);
    ins.i32_const(64);
    ins.i32_gt_s();
    ins.if_(BlockType::Empty);
    ins.local_get(Y);
    finish(b, ins, Some(NEG));
    ins.end();
    ins.local_get(Y);
    ins.i64_reinterpret_f64();
    ins.local_set(YBITS);
    // +Infinity: the previous value is the largest finite one.
    ins.local_get(YBITS);
    ins.i64_const(0x7ff0_0000_0000_0000);
    ins.i64_eq();
    ins.if_(BlockType::Empty);
    ins.f64_const(f64::MAX.into());
    ins.call(rt(b, "float_bounds"));
    ins.local_set(PARITY);
    ins.i32_const(din);
    ins.local_get(L);
    ins.local_get(K);
    ins.i32_wrap_i64();
    ins.i32_const(area(b, AREA_HI));
    ins.i32_const(meta + 8);
    ins.i32_load(mem(0, 4));
    ins.i32_const(meta + 12);
    ins.i32_load(mem(0, 4));
    ins.call(rt(b, "dec_cmp"));
    ins.local_set(CMP);
    apply_sticky(ins, CMP, TRUNC);
    ins.local_get(CMP);
    ins.i32_const(0);
    ins.i32_ge_s();
    ins.if_(BlockType::Empty);
    ins.f64_const(f64::INFINITY.into());
    finish(b, ins, Some(NEG));
    ins.end();
    ins.f64_const(f64::MAX.into());
    ins.local_set(Y);
    ins.br(0);
    ins.end();
    // Zero: the upper midpoint is the lower one of the smallest subnormal.
    ins.local_get(YBITS);
    ins.i64_eqz();
    ins.if_(BlockType::Empty);
    ins.f64_const(f64::from_bits(1).into());
    ins.call(rt(b, "float_bounds"));
    ins.local_set(PARITY);
    ins.i32_const(din);
    ins.local_get(L);
    ins.local_get(K);
    ins.i32_wrap_i64();
    ins.i32_const(area(b, AREA_LO));
    ins.i32_const(meta);
    ins.i32_load(mem(0, 4));
    ins.i32_const(meta + 4);
    ins.i32_load(mem(0, 4));
    ins.call(rt(b, "dec_cmp"));
    ins.local_set(CMP);
    apply_sticky(ins, CMP, TRUNC);
    ins.local_get(CMP);
    ins.i32_const(0);
    ins.i32_le_s();
    ins.if_(BlockType::Empty);
    ins.f64_const(0.0.into());
    finish(b, ins, Some(NEG));
    ins.end();
    ins.f64_const(f64::from_bits(1).into());
    ins.local_set(Y);
    ins.br(0);
    ins.end();
    // The interval of the candidate.
    ins.local_get(Y);
    ins.call(rt(b, "float_bounds"));
    ins.local_set(PARITY);
    ins.i32_const(din);
    ins.local_get(L);
    ins.local_get(K);
    ins.i32_wrap_i64();
    ins.i32_const(area(b, AREA_LO));
    ins.i32_const(meta);
    ins.i32_load(mem(0, 4));
    ins.i32_const(meta + 4);
    ins.i32_load(mem(0, 4));
    ins.call(rt(b, "dec_cmp"));
    ins.local_set(CMP);
    apply_sticky(ins, CMP, TRUNC);
    // Below the lower midpoint.
    ins.local_get(CMP);
    ins.i32_const(0);
    ins.i32_lt_s();
    ins.if_(BlockType::Empty);
    ins.local_get(YBITS);
    ins.i64_const(1);
    ins.i64_sub();
    ins.f64_reinterpret_i64();
    ins.local_set(Y);
    ins.br(1);
    ins.end();
    // On the lower midpoint: the even mantissa wins.
    ins.local_get(CMP);
    ins.i32_eqz();
    ins.if_(BlockType::Empty);
    ins.local_get(PARITY);
    ins.i32_eqz();
    ins.if_(BlockType::Empty);
    ins.local_get(Y);
    finish(b, ins, Some(NEG));
    ins.end();
    ins.local_get(YBITS);
    ins.i64_const(1);
    ins.i64_sub();
    ins.f64_reinterpret_i64();
    ins.local_set(Y);
    ins.br(1);
    ins.end();
    // Above the upper midpoint.
    ins.i32_const(din);
    ins.local_get(L);
    ins.local_get(K);
    ins.i32_wrap_i64();
    ins.i32_const(area(b, AREA_HI));
    ins.i32_const(meta + 8);
    ins.i32_load(mem(0, 4));
    ins.i32_const(meta + 12);
    ins.i32_load(mem(0, 4));
    ins.call(rt(b, "dec_cmp"));
    ins.local_set(CMP);
    apply_sticky(ins, CMP, TRUNC);
    ins.local_get(CMP);
    ins.i32_const(0);
    ins.i32_gt_s();
    ins.if_(BlockType::Empty);
    ins.local_get(YBITS);
    ins.i64_const(1);
    ins.i64_add();
    ins.f64_reinterpret_i64();
    ins.local_set(Y);
    ins.br(1);
    ins.end();
    // On the upper midpoint: the even mantissa wins.
    ins.local_get(CMP);
    ins.i32_eqz();
    ins.local_get(PARITY);
    ins.i32_eqz();
    ins.i32_and();
    ins.if_(BlockType::Empty);
    ins.local_get(Y);
    finish(b, ins, Some(NEG));
    ins.end();
    // Inside the interval.
    ins.local_get(CMP);
    ins.i32_const(0);
    ins.i32_lt_s();
    ins.if_(BlockType::Empty);
    ins.local_get(Y);
    finish(b, ins, Some(NEG));
    ins.end();
    // Otherwise the next value.
    ins.local_get(YBITS);
    ins.i64_const(1);
    ins.i64_add();
    ins.f64_reinterpret_i64();
    ins.local_set(Y);
    ins.br(0);
    ins.end();
    ins.end();
    ins.local_get(Y);
    finish(b, ins, Some(NEG));
}

/// Pushes `neg` and the `Some` descriptor, calls `float_some` with the value already on the stack,
/// and returns from the function.
pub(super) fn finish(b: &mut Builder, ins: &mut InstructionSink, neg: Option<u32>) {
    match neg {
        Some(n) => {
            ins.local_get(n);
        }
        None => {
            ins.i32_const(0);
        }
    };
    ins.local_get(1);
    ins.call(rt(b, "float_some"));
    ins.return_();
}
