//! The emitter: Heap IR (stage `RefCounted`) to C.
//!
//! The Heap IR already says everything the C needs: the evaluation order (ANF), where control
//! goes (structured statements, failure and defect landings), and when references are added and
//! given up (`dup` and `drop`). The emitter follows it mechanically:
//!
//! - Every IR variable is a C local (`v12`) declared at the top of its function. Values that
//!   leave a compound statement through `yield` or `break` are assigned to its destination,
//!   followed by a `goto` to the label after the statement; `recur` assigns the loop variables
//!   and jumps to the loop head.
//! - A call's defect landing is `if (em_defect != NULL) { … }` after the call, and its failure
//!   landing `if (em_failure != NULL) { … }`. `unwind` and `fail` return a dummy value.
//! - Heap objects get descriptors (`em_d3`) per shape: the constructor tag, the enum of an error
//!   value, and which slots hold references. Constructors without fields, string literals and
//!   closures without captures are static objects, which reference counting skips.

use emela_core::{Builtin, EnumId, FiberOp, HostModule, HostRef, Type, TypeId};
use emela_lir::{
    Callee, CaseKey, Const, FnId, Function, LabelId, Module, OnFail, Operand, PrimOp, PrimTy, Repr,
    RuntimeOp, SeqId, Stage, Stmt, StmtId, Suspend, SwitchOn, Term, Value, VarId, enum_repr,
    repr_of,
};
use rustc_hash::{FxHashMap, FxHashSet};

use crate::check::display_name;
use crate::names;
use crate::writer::{Writer, call, init_list, param, signature};
use crate::{CError, CErrorKind, COutput, RUNTIME_H_FILE};

/// What the generated `main` runs.
pub(crate) enum Run {
    /// The entry's `main` (its monomorphized copy), if any, and the exported fns (their copies)
    /// with their host names (`[target.c.export]`).
    Main(Option<FnId>, Vec<(FnId, Vec<String>)>),
    /// Test functions, with their names.
    Tests(Vec<(String, FnId)>),
}

pub(crate) fn emit(m: &Module, entry: &Run) -> Result<COutput, Vec<CError>> {
    assert_eq!(
        m.stage,
        Stage::RefCounted,
        "the C emitter reads the Heap IR"
    );
    let mut e = Emitter {
        m,
        fn_names: m
            .functions
            .iter()
            .map(|(id, f)| names::function(ix(id), &f.name))
            .collect(),
        descs: FxHashMap::default(),
        lits: FxHashMap::default(),
        nullary: FxHashMap::default(),
        closures: FxHashMap::default(),
        statics: Writer::new(),
        host_protos: Writer::new(),
        host_names: FxHashSet::default(),
        bundled: Vec::new(),
        host_files: Vec::new(),
        consts: Vec::new(),
        error_shows: m.error_shows.iter().copied().collect(),
        errors: Vec::new(),
    };
    let mut protos = Writer::new();
    let mut bodies = Writer::new();
    for (id, f) in m.functions.iter() {
        protos.static_proto(&e.signature(id, f, if f.constant { "_init" } else { "" }));
        if f.constant {
            protos.static_proto(&e.signature(id, f, ""));
        }
        if is_machine(f) {
            let name = &e.fn_names[ix(id)];
            protos.static_proto(&e.machine_signature(id, f));
            protos.static_proto(&signature(
                "em_word",
                &format!("{name}_resume"),
                ["em_ref", "em_word"],
            ));
        }
    }
    for (id, f) in m.functions.iter() {
        if let Some(ext) = &f.external {
            e.external(&mut bodies, id, f, ext);
        } else {
            e.function(&mut bodies, id, f);
        }
        bodies.blank();
    }
    match entry {
        Run::Main(main, exports) => {
            e.c_exports(&mut bodies, exports);
            e.c_main(&mut bodies, *main);
        }
        Run::Tests(tests) => e.c_test_main(&mut bodies, tests),
    }
    if !e.errors.is_empty() {
        return Err(e.errors);
    }
    let mut out = Writer::new();
    out.comment("Generated by Emela.");
    out.include(RUNTIME_H_FILE);
    out.blank();
    if !e.host_protos.is_empty() {
        out.comment("Host functions (spec 12.4).");
        out.append(std::mem::take(&mut e.host_protos));
        out.blank();
    }
    out.append(protos);
    out.blank();
    out.append(std::mem::take(&mut e.statics));
    out.blank();
    out.append(bodies);
    let bundled = m
        .core
        .bundled_files
        .iter()
        .filter(|file| e.bundled.contains(&file.path))
        .map(|file| (file.path.clone(), file.contents.clone()))
        .collect();
    Ok(COutput {
        main: out.finish(),
        bundled,
        host_files: e.host_files,
    })
}

fn ix<T>(id: la_arena::Idx<T>) -> usize {
    u32::from(id.into_raw()) as usize
}

/// The shape of a heap object made by the program.
#[derive(Debug, Clone, PartialEq, Eq, Hash)]
struct DescKey {
    tag: u32,
    /// The enum index of an error value, or -1.
    enum_id: i32,
    name: String,
    show: Option<FnId>,
    refs: Vec<bool>,
}

struct Emitter<'m> {
    m: &'m Module,
    fn_names: Vec<String>,
    descs: FxHashMap<DescKey, usize>,
    lits: FxHashMap<Vec<u8>, usize>,
    /// Static objects of constructors without fields, by descriptor.
    nullary: FxHashMap<usize, usize>,
    /// Static closure records without captures, by function.
    closures: FxHashMap<FnId, usize>,
    /// Descriptors, literals and other static data, in order of first use.
    statics: Writer,
    host_protos: Writer,
    host_names: FxHashSet<String>,
    bundled: Vec<String>,
    host_files: Vec<String>,
    /// The const functions, for the cleanup at exit.
    consts: Vec<FnId>,
    /// The `show` of each error enum's descriptor (`emela_lir::Module::error_shows`), which shows a
    /// failure that reaches the entry.
    error_shows: FxHashMap<EnumId, FnId>,
    errors: Vec<CError>,
}

/// Where a `yield` goes: the destination of the enclosing statement and the label after it.
#[derive(Clone)]
struct Yield {
    dst: Option<VarId>,
    end: String,
    /// Whether the end of the sequence is right before the label, so that its final `yield`
    /// needs no `goto`.
    falls: bool,
}

impl Yield {
    fn new(dst: Option<VarId>, end: String) -> Self {
        Yield {
            dst,
            end,
            falls: false,
        }
    }

    fn falling(&self) -> Self {
        Yield {
            falls: true,
            ..self.clone()
        }
    }
}

/// The function being emitted.
struct Cx<'a> {
    f: &'a Function,
    ret: Repr,
    /// The body, one level in.
    w: Writer,
    /// Blocks by label: their destination and end label.
    labels: FxHashMap<LabelId, Yield>,
    /// The enclosing loops, innermost last: their variables and head label.
    loops: Vec<(Vec<VarId>, String)>,
    used_labels: FxHashSet<String>,
    /// For a suspending function emitted as a state machine, its C name (its resume function
    /// is `name_resume`).
    machine: Option<String>,
    /// The resume points met so far.
    resumes: Vec<ResumePoint>,
}

/// A resume point of a state machine: what the frame of `state` restores, and where the input
/// goes.
struct ResumePoint {
    state: u32,
    saved: Vec<VarId>,
    dst: Option<VarId>,
}

/// Whether the function is emitted as a state machine: a suspending function with suspension
/// points.
fn is_machine(f: &Function) -> bool {
    f.suspends
        && f.body.is_some()
        && f.stmts.iter().any(|(_, s)| {
            matches!(
                s,
                Stmt::Let {
                    on_suspend: Some(_),
                    ..
                }
            )
        })
}

/// The entry of a state machine with a frame: restores the saved variables of the frame's state,
/// frees the frame, takes the input as the suspended value's result and jumps after it.
fn resume_dispatch(w: &mut Writer, f: &Function, resumes: &[ResumePoint]) {
    w.if_("em_fr != NULL", |w| {
        w.switch("em_fr->slots[1].i", |w| {
            for r in resumes {
                w.case(&r.state.to_string(), |w| {
                    for (i, &v) in r.saved.iter().enumerate() {
                        w.assign(&var(v), &format!("em_fr->{}", slot(i + 3, f.vars[v].repr)));
                    }
                    w.stmt("em_frame_free(em_fr)");
                    if let Some(d) = r.dst {
                        w.assign(&var(d), &format!("em_in.{}", acc(f.vars[d].repr)));
                    }
                    w.goto(&format!("em_r{}", r.state));
                });
            }
            w.default_case(|w| w.stmt("em_unreachable()"));
        });
    });
}

impl Cx<'_> {
    fn goto(&mut self, label: &str) {
        self.used_labels.insert(label.to_owned());
        self.w.goto(label);
    }

    /// The label line, if anything jumps to it.
    fn label(&mut self, label: &str) {
        if self.used_labels.contains(label) {
            self.w.label(label);
        }
    }

    /// What `unwind` and `fail` return.
    fn dummy_return(&mut self) {
        self.w.ret(dummy(self.ret));
    }
}

/// The value `unwind`, `fail` and failed conversions return in a function returning `r`.
fn dummy(r: Repr) -> Option<&'static str> {
    if r == Repr::Void { None } else { Some("0") }
}

/// `slots[i].a`: the member of a slot holding a value of the representation.
fn slot(i: usize, r: Repr) -> String {
    format!("slots[{i}].{}", acc(r))
}

/// `(em_word){.a = value}`: a word holding a value of the representation.
fn word_of(r: Repr, value: &str) -> String {
    format!("(em_word){{.{} = {value}}}", acc(r))
}

fn var(v: VarId) -> String {
    format!("v{}", ix(v))
}

pub(crate) fn cty(r: Repr) -> &'static str {
    match r {
        Repr::I32 => "int32_t",
        Repr::I64 => "int64_t",
        Repr::F64 => "double",
        Repr::Ref => "em_ref",
        Repr::Void => "void",
    }
}

/// The member of `em_word` holding a value of the representation.
fn acc(r: Repr) -> &'static str {
    match r {
        Repr::I32 => "i",
        Repr::I64 => "l",
        Repr::F64 => "f",
        Repr::Ref => "p",
        Repr::Void => "l",
    }
}

fn stmt_label(s: StmtId, what: &str) -> String {
    format!("s{}_{what}", ix(s))
}

/// How an external function's value crosses to C (spec 12.4).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum HostTy {
    Int,
    Int64,
    Float,
    Bool,
    String,
    Unit,
    Handle,
}

impl HostTy {
    fn param(self) -> &'static str {
        match self {
            HostTy::Int => "int32_t",
            HostTy::Int64 => "int64_t",
            HostTy::Float => "double",
            HostTy::Bool => "bool",
            HostTy::String => "const char *",
            HostTy::Unit => "void",
            HostTy::Handle => "void *",
        }
    }

    fn ret(self) -> &'static str {
        match self {
            HostTy::String => "char *",
            other => other.param(),
        }
    }
}

impl<'m> Emitter<'m> {
    fn core(&self) -> &'m emela_core::Module {
        &self.m.core
    }

    fn repr(&self, ty: TypeId) -> Repr {
        repr_of(self.core(), ty)
    }

    fn internal(&mut self, message: impl Into<String>) {
        self.errors.push(CError::new(
            CErrorKind::Internal,
            format!("internal error in the C emitter: {}", message.into()),
        ));
    }

    /// `RET name(PARAMS)`.
    fn signature(&self, id: FnId, f: &Function, suffix: &str) -> String {
        let params = f
            .params
            .iter()
            .map(|&p| param(cty(f.vars[p].repr), &var(p)));
        signature(
            cty(self.repr(f.ret)),
            &format!("{}{suffix}", self.fn_names[ix(id)]),
            params,
        )
    }

    fn operand(&mut self, o: &Operand) -> String {
        match o {
            Operand::Var(v) => var(*v),
            Operand::Const(c) => self.constant(c),
        }
    }

    fn constant(&mut self, c: &Const) -> String {
        match c {
            Const::Int(n) => names::int32(*n),
            Const::Int64(n) => names::int64(*n),
            Const::Float(x) => names::float(*x),
            Const::Bool(b) => if *b { "1" } else { "0" }.to_owned(),
            Const::String(s) => self.literal(s.as_bytes()),
            Const::Unit => "0".to_owned(),
        }
    }

    fn operand_repr(f: &Function, o: &Operand) -> Repr {
        match o {
            Operand::Var(v) => f.vars[*v].repr,
            Operand::Const(c) => c.repr(),
        }
    }

    /// A static string object.
    fn literal(&mut self, bytes: &[u8]) -> String {
        let n = match self.lits.get(bytes) {
            Some(&n) => n,
            None => {
                let n = self.lits.len();
                self.lits.insert(bytes.to_vec(), n);
                self.statics.decl(
                    &format!(
                        "static struct {{ em_hdr hdr; int64_t len; char bytes[{}]; }}",
                        bytes.len() + 1
                    ),
                    &format!("em_s{n}"),
                    Some(&init_list([
                        "EM_STATIC_HDR(&em_desc_string)".to_owned(),
                        bytes.len().to_string(),
                        names::string_literal(bytes),
                    ])),
                );
                n
            }
        };
        format!("((em_ref)&em_s{n})")
    }

    /// The descriptor's C name.
    fn desc(&mut self, key: DescKey) -> usize {
        if let Some(&n) = self.descs.get(&key) {
            return n;
        }
        let n = self.descs.len();
        let refs = if key.refs.is_empty() {
            "NULL".to_owned()
        } else {
            let flags = key.refs.iter().map(|&r| if r { "1" } else { "0" });
            self.statics.decl(
                "static const uint8_t",
                &format!("em_r{n}[]"),
                Some(&init_list(flags)),
            );
            format!("em_r{n}")
        };
        let show = match key.show {
            Some(f) => self.fn_names[ix(f)].clone(),
            None => "NULL".to_owned(),
        };
        self.statics.decl(
            "static const em_desc",
            &format!("em_d{n}"),
            Some(&init_list([
                "EM_KIND_FIELDS".to_owned(),
                key.refs.len().to_string(),
                key.tag.to_string(),
                key.enum_id.to_string(),
                names::string_literal(key.name.as_bytes()),
                show,
                refs,
            ])),
        );
        self.descs.insert(key, n);
        n
    }

    fn function(&mut self, out: &mut Writer, id: FnId, f: &Function) {
        let Some(body) = f.body else {
            self.internal(format!("fn {} has no body", f.name));
            return;
        };
        let ret = self.repr(f.ret);
        let machine = is_machine(f).then(|| self.fn_names[ix(id)].clone());
        let mut cx = Cx {
            f,
            ret,
            w: Writer::indented(1),
            labels: FxHashMap::default(),
            loops: Vec::new(),
            used_labels: FxHashSet::default(),
            machine: machine.clone(),
            resumes: Vec::new(),
        };
        self.seq(&mut cx, body, None);
        let sig = match &machine {
            Some(_) => self.machine_signature(id, f),
            None => self.signature(id, f, if f.constant { "_init" } else { "" }),
        };
        out.comment(&f.name);
        out.static_func(&sig, |w| {
            for (v, data) in f.vars.iter() {
                if !f.params.contains(&v) {
                    w.decl(cty(data.repr), &var(v), Some("0"));
                }
            }
            if machine.is_some() {
                resume_dispatch(w, f, &cx.resumes);
            }
            w.append(cx.w);
        });
        if let Some(name) = &machine {
            self.machine_wrappers(out, id, f, name, ret);
        }
        if f.constant {
            self.const_wrapper(out, id, f, ret);
        }
    }

    /// `RET name_sm(em_ref em_fr, em_word em_in, PARAMS)`: the body of a suspending function,
    /// entered without a frame by the function itself and with one by the driver loop.
    fn machine_signature(&self, id: FnId, f: &Function) -> String {
        let mut params = vec![param("em_ref", "em_fr"), param("em_word", "em_in")];
        params.extend(
            f.params
                .iter()
                .map(|&p| param(cty(f.vars[p].repr), &var(p))),
        );
        signature(
            cty(self.repr(f.ret)),
            &format!("{}_sm", self.fn_names[ix(id)]),
            params,
        )
    }

    /// The function itself (entering the state machine without a frame) and its resume function
    /// for the driver loop (entering it with a frame and the input, returning the result as a
    /// word).
    fn machine_wrappers(&self, out: &mut Writer, id: FnId, f: &Function, name: &str, ret: Repr) {
        let machine = format!("{name}_sm");
        let mut args = vec!["NULL".to_owned(), "(em_word){.l = 0}".to_owned()];
        args.extend(f.params.iter().map(|&p| var(p)));
        let enter = call(&machine, &args);
        out.static_func(&self.signature(id, f, ""), |w| {
            if ret == Repr::Void {
                w.stmt(&enter);
            } else {
                w.ret(Some(&enter));
            }
        });
        let mut zeros = vec!["fr".to_owned(), "in".to_owned()];
        zeros.extend(f.params.iter().map(|&p| match f.vars[p].repr {
            Repr::Ref => "NULL".to_owned(),
            _ => "0".to_owned(),
        }));
        let resume = call(&machine, &zeros);
        let sig = signature(
            "em_word",
            &format!("{name}_resume"),
            [param("em_ref", "fr"), param("em_word", "in")],
        );
        out.static_func(&sig, |w| {
            w.decl("em_word", "out", None);
            w.assign("out.l", "0");
            if ret == Repr::Void {
                w.stmt(&resume);
            } else {
                w.assign(&format!("out.{}", acc(ret)), &resume);
            }
            w.ret(Some("out"));
        });
    }

    /// The function a const's callers call: evaluates the body once and remembers the value or
    /// the defect (spec 5.6).
    fn const_wrapper(&mut self, out: &mut Writer, id: FnId, f: &Function, ret: Repr) {
        let n = ix(id);
        let name = &self.fn_names[n];
        self.statics.decl(
            "static em_const",
            &format!("em_c{n}"),
            Some(&init_list([
                "0",
                "{0}",
                if ret == Repr::Ref { "true" } else { "false" },
                "NULL",
                names::string_literal(f.name.as_bytes()).as_str(),
            ])),
        );
        let cell = format!("&em_c{n}");
        let enter = format!("!{}", call("em_const_enter", [cell.as_str(), "&w"]));
        let leave = call("em_const_leave", [cell.as_str(), "w"]);
        let init = call(&format!("{name}_init"), [""; 0]);
        out.static_func(&self.signature(id, f, ""), |w| {
            w.decl("em_word", "w", None);
            if ret == Repr::Void {
                w.if_return(&enter, None);
                w.stmt(&init);
                w.assign("w.l", "0");
                w.stmt(&leave);
            } else {
                let a = acc(ret);
                w.if_return(&enter, Some(&format!("w.{a}")));
                w.decl(cty(ret), "v", Some(&init));
                w.assign("w.l", "0");
                w.assign(&format!("w.{a}"), "v");
                w.stmt(&leave);
                w.ret(Some("v"));
            }
        });
        self.consts.push(id);
    }

    fn seq(&mut self, cx: &mut Cx<'_>, id: SeqId, y: Option<&Yield>) {
        let f = cx.f;
        let seq = &f.seqs[id];
        for &s in &seq.stmts {
            self.stmt(cx, s);
        }
        self.term(cx, &seq.term, y);
    }

    fn term(&mut self, cx: &mut Cx<'_>, term: &Term, y: Option<&Yield>) {
        match term {
            Term::Yield(v) => {
                let Some(y) = y else {
                    self.internal(format!("yield without a target in {}", cx.f.name));
                    return;
                };
                if let (Some(dst), Some(v)) = (y.dst, v) {
                    let v = self.operand(v);
                    cx.w.assign(&var(dst), &v);
                }
                if !y.falls {
                    cx.goto(&y.end);
                }
            }
            Term::Return(v) => match v {
                Some(v) => {
                    let v = self.operand(v);
                    cx.w.ret(Some(&v));
                }
                None => cx.dummy_return(),
            },
            Term::Fail(v) => {
                let v = self.operand(v);
                cx.w.assign("em_failure", &v);
                cx.dummy_return();
            }
            Term::Break { label, value } => {
                let Some(target) = cx.labels.get(label).cloned() else {
                    self.internal(format!("break to an unknown label in {}", cx.f.name));
                    return;
                };
                if let (Some(dst), Some(v)) = (target.dst, value) {
                    let v = self.operand(v);
                    cx.w.assign(&var(dst), &v);
                }
                cx.goto(&target.end);
            }
            Term::Recur(args) => {
                let Some((vars, head)) = cx.loops.last().cloned() else {
                    self.internal(format!("recur outside a loop in {}", cx.f.name));
                    return;
                };
                // Parallel assignment: the new values may read the old ones.
                let values: Vec<String> = args.iter().map(|a| self.operand(a)).collect();
                cx.w.block_begin();
                for (i, (&v, value)) in vars.iter().zip(&values).enumerate() {
                    cx.w.decl(cty(cx.f.vars[v].repr), &format!("t{i}"), Some(value));
                }
                for (i, &v) in vars.iter().enumerate() {
                    cx.w.assign(&var(v), &format!("t{i}"));
                }
                cx.goto(&head);
                cx.w.end();
            }
            Term::Unwind => cx.dummy_return(),
            Term::Unreachable => cx.w.stmt("em_unreachable()"),
            Term::Defect(..) => self.internal(format!("defect left in {}", cx.f.name)),
        }
    }

    /// Emits `body` into a separate writer (to decide afterwards whether a label before it is
    /// used).
    fn capture(&mut self, cx: &mut Cx<'_>, body: impl FnOnce(&mut Self, &mut Cx<'_>)) -> Writer {
        let aside = cx.w.aside();
        let saved = std::mem::replace(&mut cx.w, aside);
        body(self, cx);
        std::mem::replace(&mut cx.w, saved)
    }

    fn stmt(&mut self, cx: &mut Cx<'_>, id: StmtId) {
        let f = cx.f;
        match &f.stmts[id] {
            Stmt::Let {
                dst,
                value,
                on_defect,
                on_suspend,
            } => {
                // Suspending code called where nothing may suspend runs in place (spec 8.7).
                let sync = !f.suspends && emela_lir::may_suspend(value);
                if sync {
                    cx.w.stmt("em_sync_enter()");
                }
                self.value(cx, *dst, value);
                if sync {
                    cx.w.stmt("em_sync_leave()");
                }
                if let Some(edge) = on_suspend {
                    self.suspend_edge(cx, edge, *dst);
                }
                if let Some(landing) = on_defect {
                    cx.w.if_begin("em_defect != NULL");
                    self.seq(cx, *landing, None);
                    cx.w.end();
                }
                let on_fail = match value {
                    Value::Call { on_fail, .. } | Value::Fiber { on_fail, .. } => on_fail,
                    _ => &None,
                };
                match on_fail {
                    Some(OnFail::Handle { error, body }) => {
                        cx.w.if_begin("em_failure != NULL");
                        cx.w.assign(&var(*error), "em_failure");
                        cx.w.assign("em_failure", "NULL");
                        self.seq(cx, *body, None);
                        cx.w.end();
                    }
                    Some(_) => self.internal(format!("Flow IR failure edge in {}", f.name)),
                    None => {}
                }
            }
            Stmt::If {
                dst,
                cond,
                then,
                else_,
            } => {
                let y = Yield::new(*dst, stmt_label(id, "end"));
                let cond = self.operand(cond);
                cx.w.if_begin(&cond);
                self.seq(cx, *then, Some(&y));
                cx.w.else_begin();
                self.seq(cx, *else_, Some(&y.falling()));
                cx.w.end();
                cx.label(&y.end);
            }
            Stmt::Switch {
                dst,
                on,
                cases,
                default,
            } => {
                let y = Yield::new(*dst, stmt_label(id, "end"));
                let scrutinee = match on {
                    SwitchOn::Tag(v) if f.vars[*v].repr == Repr::Ref => call("em_tag", [var(*v)]),
                    SwitchOn::Tag(v) | SwitchOn::Lit(v) => var(*v),
                };
                cx.w.switch_begin(&scrutinee);
                for case in cases {
                    let key = match &case.key {
                        CaseKey::Variant(k) => k.to_string(),
                        CaseKey::Lit(c) => self.constant(c),
                    };
                    cx.w.case_begin(&key);
                    self.seq(cx, case.body, Some(&y));
                    cx.w.end();
                }
                match default {
                    Some(d) => {
                        cx.w.default_begin();
                        self.seq(cx, *d, Some(&y));
                        cx.w.end();
                    }
                    None => cx.w.default_stmt("em_unreachable()"),
                }
                cx.w.switch_end();
                cx.label(&y.end);
            }
            Stmt::Loop {
                dst,
                vars,
                inits,
                body,
            } => {
                for (&v, init) in vars.iter().zip(inits) {
                    let init = self.operand(init);
                    cx.w.assign(&var(v), &init);
                }
                let y = Yield::new(*dst, stmt_label(id, "end")).falling();
                let head = stmt_label(id, "head");
                cx.loops.push((vars.clone(), head.clone()));
                let text = self.capture(cx, |e, cx| {
                    cx.w.block_begin();
                    e.seq(cx, *body, Some(&y));
                    cx.w.end();
                });
                cx.loops.pop();
                cx.label(&head);
                cx.w.append(text);
                cx.label(&y.end);
            }
            Stmt::Block { dst, label, body } => {
                let y = Yield::new(*dst, stmt_label(id, "end"));
                cx.labels.insert(*label, y.clone());
                cx.w.block_begin();
                self.seq(cx, *body, Some(&y.falling()));
                cx.w.end();
                cx.label(&y.end);
            }
            Stmt::Protect { .. } => self.internal(format!("protect left in {}", f.name)),
            Stmt::Dup(v) => cx.w.stmt(&call("em_dup", [var(*v)])),
            Stmt::Drop(v) => cx.w.stmt(&call("em_drop", [var(*v)])),
        }
    }

    /// A suspension edge: when the value came back suspended, the function pushes a frame with
    /// the state and the saved variables onto the continuation and returns. Its resume point,
    /// where the frame's entry jumps with the input, is right after (before the landings).
    fn suspend_edge(&mut self, cx: &mut Cx<'_>, edge: &Suspend, dst: Option<VarId>) {
        let f = cx.f;
        let Some(name) = cx.machine.clone() else {
            self.internal(format!(
                "a suspension edge outside a state machine in {}",
                f.name
            ));
            return;
        };
        let mut refs = vec![false, false, true];
        refs.extend(edge.saved.iter().map(|&v| f.vars[v].repr == Repr::Ref));
        let desc = self.desc(DescKey {
            tag: 0,
            enum_id: -1,
            name: display_name(&f.name).to_owned(),
            show: None,
            refs,
        });
        cx.w.if_begin("em_suspending");
        let frame = call(
            "em_frame_new",
            [
                format!("&em_d{desc}"),
                format!("{name}_resume"),
                edge.state.to_string(),
                edge.saved.len().to_string(),
            ],
        );
        cx.w.decl("em_ref", "fr", Some(&frame));
        for (i, &v) in edge.saved.iter().enumerate() {
            let r = f.vars[v].repr;
            cx.w.assign(&format!("fr->slots[{}]", i + 3), &word_of(r, &var(v)));
        }
        cx.w.stmt("em_frame_push(fr)");
        cx.dummy_return();
        cx.w.end();
        cx.w.label_at_margin(&format!("em_r{}", edge.state));
        cx.resumes.push(ResumePoint {
            state: edge.state,
            saved: edge.saved.clone(),
            dst,
        });
    }

    /// `dst = <expression>;`, or the expression alone without a destination.
    fn assign(cx: &mut Cx<'_>, dst: Option<VarId>, expr: &str) {
        match dst {
            Some(d) => cx.w.assign(&var(d), expr),
            None => cx.w.stmt(expr),
        }
    }

    /// `(em_word){.i = x}` for a slot.
    fn word(&mut self, f: &Function, o: &Operand) -> String {
        let r = Self::operand_repr(f, o);
        let v = self.operand(o);
        word_of(r, &v)
    }

    /// Allocates an object of `desc` with `args` in its slots (consumed: the IR passes their
    /// references on).
    fn alloc(
        &mut self,
        cx: &mut Cx<'_>,
        dst: Option<VarId>,
        desc: usize,
        first: Option<String>,
        args: &[Operand],
    ) {
        let n = args.len() + usize::from(first.is_some());
        let target = match dst {
            Some(d) => var(d),
            None => {
                self.internal(format!("allocation without a destination in {}", cx.f.name));
                return;
            }
        };
        cx.w.assign(
            &target,
            &call("em_alloc", [format!("&em_d{desc}"), n.to_string()]),
        );
        let mut slot = 0;
        if let Some(first) = first {
            cx.w.assign(&format!("{target}->slots[0]"), &first);
            slot = 1;
        }
        for a in args {
            let w = self.word(cx.f, a);
            cx.w.assign(&format!("{target}->slots[{slot}]"), &w);
            slot += 1;
        }
    }

    /// Which slots of an object made from `args` hold references. Taken from the arguments'
    /// representations: after monomorphisation they are fixed per type.
    fn refs_of(f: &Function, args: &[Operand]) -> Vec<bool> {
        args.iter()
            .map(|a| Self::operand_repr(f, a) == Repr::Ref)
            .collect()
    }

    fn value(&mut self, cx: &mut Cx<'_>, dst: Option<VarId>, value: &Value) {
        let f = cx.f;
        match value {
            Value::Const(c) => {
                let c = self.constant(c);
                Self::assign(cx, dst, &c);
            }
            Value::Prim { op, ty, args } => {
                let a: Vec<String> = args.iter().map(|o| self.operand(o)).collect();
                let e = prim(*op, *ty, &a);
                Self::assign(cx, dst, &e);
            }
            Value::Call { callee, args, .. } => self.call(cx, dst, callee, args),
            Value::Builtin { op, args } => self.builtin(cx, dst, *op, args),
            Value::Make { ctor, args } => {
                let core = self.core();
                let def = &core.enums[ctor.enum_id];
                if enum_repr(core, ctor.enum_id) == Repr::I32 {
                    Self::assign(cx, dst, &ctor.variant.to_string());
                    return;
                }
                let key = DescKey {
                    tag: ctor.variant as u32,
                    enum_id: if def.error {
                        ix(ctor.enum_id) as i32
                    } else {
                        -1
                    },
                    name: def.variants[ctor.variant].name.clone(),
                    show: if def.error {
                        self.error_shows.get(&ctor.enum_id).copied()
                    } else {
                        None
                    },
                    refs: Self::refs_of(f, args),
                };
                let desc = self.desc(key);
                if args.is_empty() {
                    let obj = self.nullary(desc);
                    Self::assign(cx, dst, &obj);
                } else {
                    self.alloc(cx, dst, desc, None, args);
                }
            }
            Value::Field { base, index, .. } | Value::TupleGet { base, index } => {
                if let Some(d) = dst {
                    let r = f.vars[d].repr;
                    cx.w.assign(&var(d), &format!("{}->{}", var(*base), slot(*index, r)));
                }
            }
            Value::Tag(v) => {
                let e = if f.vars[*v].repr == Repr::Ref {
                    format!("(int32_t){}", call("em_tag", [var(*v)]))
                } else {
                    var(*v)
                };
                Self::assign(cx, dst, &e);
            }
            Value::Tuple(elems) => {
                let desc = self.desc(DescKey {
                    tag: 0,
                    enum_id: -1,
                    name: "tuple".into(),
                    show: None,
                    refs: Self::refs_of(f, elems),
                });
                self.alloc(cx, dst, desc, None, elems);
            }
            Value::List { elems, tail } => {
                let Some(d) = dst else {
                    self.internal(format!("list without a destination in {}", f.name));
                    return;
                };
                let tail = match tail {
                    Some(t) => self.operand(t),
                    None => "NULL".to_owned(),
                };
                cx.w.assign(&var(d), &tail);
                for e in elems.iter().rev() {
                    let r = Self::operand_repr(f, e) == Repr::Ref;
                    let w = self.word(f, e);
                    let flag = if r { "true" } else { "false" };
                    cx.w.assign(&var(d), &call("em_cons", [w, flag.to_owned(), var(d)]));
                }
            }
            Value::ListIsEmpty(v) => Self::assign(cx, dst, &format!("({} == NULL)", var(*v))),
            Value::ListHead(v) => {
                if let Some(d) = dst {
                    let r = f.vars[d].repr;
                    cx.w.assign(&var(d), &format!("{}->{}", var(*v), slot(0, r)));
                }
            }
            Value::ListTail(v) => Self::assign(cx, dst, &format!("{}->slots[1].p", var(*v))),
            Value::FnRef(_) | Value::Closure(_) => {
                self.internal(format!("unconverted closure in {}", f.name));
            }
            Value::MakeClosure { function, captures } => {
                let fname = self.fn_names[ix(*function)].clone();
                if captures.is_empty() {
                    let obj = self.static_closure(*function);
                    Self::assign(cx, dst, &obj);
                    return;
                }
                let args: Vec<Operand> = captures.iter().map(|&c| Operand::Var(c)).collect();
                let mut refs = vec![false];
                refs.extend(Self::refs_of(f, &args));
                let desc = self.desc(DescKey {
                    tag: 0,
                    enum_id: -1,
                    name: display_name(&self.m.functions[*function].name).to_owned(),
                    show: None,
                    refs,
                });
                self.alloc(
                    cx,
                    dst,
                    desc,
                    Some(format!("(em_word){{.fn = (em_fnptr){fname}}}")),
                    &args,
                );
            }
            Value::EnvGet { env, index } => {
                if let Some(d) = dst {
                    let r = f.vars[d].repr;
                    cx.w.assign(&var(d), &format!("{}->{}", var(*env), slot(index + 1, r)));
                }
            }
            Value::EvLookup { ev, effect } => {
                let e = call("em_ev_lookup", [var(*ev), ix(*effect).to_string()]);
                Self::assign(cx, dst, &e);
            }
            Value::EvExtend { base, bindings } => {
                let Some(d) = dst else {
                    self.internal(format!("evidence without a destination in {}", f.name));
                    return;
                };
                let base = base.map_or_else(|| "NULL".to_owned(), var);
                let n = bindings.len();
                cx.w.assign(&var(d), &call("em_ev_new", [base, n.to_string()]));
                for (i, (effect, h)) in bindings.iter().enumerate() {
                    cx.w.stmt(&call(
                        "em_ev_set",
                        [
                            var(d),
                            n.to_string(),
                            i.to_string(),
                            ix(*effect).to_string(),
                            var(*h),
                        ],
                    ));
                }
            }
            Value::Handler { name, ops, .. } => {
                let mut refs = vec![false];
                refs.extend(std::iter::repeat_n(true, ops.len()));
                let desc = self.desc(DescKey {
                    tag: 0,
                    enum_id: -1,
                    name: name.clone(),
                    show: None,
                    refs,
                });
                let args: Vec<Operand> = ops.iter().map(|&o| Operand::Var(o)).collect();
                self.alloc(cx, dst, desc, Some("(em_word){.i = 0}".into()), &args);
            }
            Value::Fiber { op, args, .. } => self.fiber(cx, dst, *op, args),
            Value::IsError { error, enum_id } => Self::assign(
                cx,
                dst,
                &call("em_is_error", [var(*error), ix(*enum_id).to_string()]),
            ),
            Value::AsError { error, .. } => Self::assign(cx, dst, &var(*error)),
            Value::Runtime { op, args } => {
                let a: Vec<String> = args.iter().map(|o| self.operand(o)).collect();
                let e = match op {
                    RuntimeOp::ShowString => call("em_show_string", &a[..1]),
                    RuntimeOp::DebugPrint => call("em_debug_print", &a[..1]),
                    RuntimeOp::Retire => call("em_retire", &a[..2]),
                    RuntimeOp::Defect => call("em_raise", &a[..1]),
                    RuntimeOp::DefectAt => call("em_raise_at", &a[..2]),
                    RuntimeOp::DefectTake => call("em_defect_take", [""; 0]),
                    RuntimeOp::DefectResume => call("em_defect_resume", &a[..1]),
                    RuntimeOp::Hold => call("em_hold", [""; 0]),
                    RuntimeOp::Unhold => call("em_unhold", [""; 0]),
                    RuntimeOp::Yield => call("em_yield", ["false"]),
                    RuntimeOp::YieldPerform => call("em_yield", ["true"]),
                };
                Self::assign(cx, dst, &e);
            }
            Value::Coerce(v) => {
                let Some(d) = dst else { return };
                let (from, to) = (f.vars[*v].repr, f.vars[d].repr);
                let e = if from == to {
                    var(*v)
                } else if to == Repr::Ref {
                    call("em_box", [word_of(from, &var(*v))])
                } else {
                    format!("{}->{}", var(*v), slot(0, to))
                };
                cx.w.assign(&var(d), &e);
            }
        }
    }

    /// The representation of the first type argument of the enum type `ty` (`Exit[A, E]`,
    /// `Option[A]`), or of the value of the function type `ty`.
    fn inner_repr(&self, ty: TypeId) -> Repr {
        match self.core().ty(ty) {
            Type::Enum(_, args) => args.first().map_or(Repr::Void, |&a| self.repr(a)),
            Type::Fn(ft) => self.repr(ft.ret),
            _ => Repr::Ref,
        }
    }

    /// A concurrency operation: a call of the runtime (spec chapter 11). The runtime moves values
    /// of any type, so it is told their representation.
    fn fiber(&mut self, cx: &mut Cx<'_>, dst: Option<VarId>, op: FiberOp, args: &[Operand]) {
        let f = cx.f;
        let a: Vec<String> = args.iter().map(|o| self.operand(o)).collect();
        let arg_ty = |i: usize| match args.get(i) {
            Some(Operand::Var(v)) => Some(f.vars[*v].ty),
            _ => None,
        };
        let dst_repr = dst.map_or(Repr::Void, |d| f.vars[d].repr);
        let dst_ty = dst.map(|d| f.vars[d].ty);
        // `name(a0, REPR)`: an operation told the representation of the value it moves.
        let op_call = |name: &str, repr: Repr| call(name, [a[0].as_str(), repr_code(repr)]);
        // The word an operation returns, unpacked into the destination.
        let word = |cx: &mut Cx<'_>, expr: String| match dst {
            Some(d) => {
                cx.w.assign(&var(d), &format!("{expr}.{}", acc(f.vars[d].repr)))
            }
            None => cx.w.stmt(&format!("(void){expr}")),
        };
        match op {
            FiberOp::Scope { .. } => {
                let repr = arg_ty(0).map_or(Repr::Void, |t| self.inner_repr(t));
                word(cx, op_call("em_fiber_scope", repr));
            }
            FiberOp::Fork => Self::assign(cx, dst, &call("em_fiber_fork", &a[..2])),
            FiberOp::Deferred => Self::assign(cx, dst, &call("em_fiber_deferred", &a[..1])),
            FiberOp::Join => word(cx, op_call("em_fiber_join", dst_repr)),
            FiberOp::Await { .. } => {
                let repr = dst_ty.map_or(Repr::Void, |t| self.inner_repr(t));
                Self::assign(cx, dst, &op_call("em_fiber_await", repr));
            }
            FiberOp::Interrupt => cx.w.stmt(&call("em_fiber_interrupt", &a[..1])),
            FiberOp::Attempt { .. } => {
                let repr = arg_ty(0).map_or(Repr::Void, |t| self.inner_repr(t));
                Self::assign(cx, dst, &op_call("em_fiber_attempt", repr));
            }
            FiberOp::Complete => {
                let repr = args.get(1).map_or(Repr::Void, |o| Self::operand_repr(f, o));
                let w = match args.get(1) {
                    Some(o) if repr != Repr::Void => self.word(f, o),
                    _ => "(em_word){.l = 0}".to_owned(),
                };
                let e = call(
                    "em_deferred_complete",
                    [a[0].as_str(), w.as_str(), repr_code(repr)],
                );
                Self::assign(cx, dst, &e);
            }
            FiberOp::DeferredAwait => word(cx, op_call("em_deferred_await", dst_repr)),
            FiberOp::Poll => {
                let repr = dst_ty.map_or(Repr::Void, |t| self.inner_repr(t));
                Self::assign(cx, dst, &op_call("em_deferred_poll", repr));
            }
            FiberOp::CauseKind { .. } => {
                Self::assign(cx, dst, &call("em_cause_kind", &a[..1]));
            }
            FiberOp::CauseToString => {
                Self::assign(cx, dst, &call("em_cause_to_string", &a[..1]));
            }
            FiberOp::CauseRaise { .. } => cx.w.stmt(&call("em_cause_raise", &a[..1])),
        }
    }

    fn nullary(&mut self, desc: usize) -> String {
        let n = match self.nullary.get(&desc) {
            Some(&n) => n,
            None => {
                let n = self.nullary.len();
                self.nullary.insert(desc, n);
                self.statics.decl(
                    "static em_hdr",
                    &format!("em_n{n}"),
                    Some(&format!("EM_STATIC_HDR(&em_d{desc})")),
                );
                n
            }
        };
        format!("((em_ref)&em_n{n})")
    }

    fn static_closure(&mut self, function: FnId) -> String {
        let n = match self.closures.get(&function) {
            Some(&n) => n,
            None => {
                let n = self.closures.len();
                self.closures.insert(function, n);
                let desc = self.desc(DescKey {
                    tag: 0,
                    enum_id: -1,
                    name: display_name(&self.m.functions[function].name).to_owned(),
                    show: None,
                    refs: vec![false],
                });
                let fn_word = format!("{{.fn = (em_fnptr){}}}", self.fn_names[ix(function)]);
                self.statics.decl(
                    "static struct { em_hdr hdr; em_word fn; }",
                    &format!("em_k{n}"),
                    Some(&init_list([format!("EM_STATIC_HDR(&em_d{desc})"), fn_word])),
                );
                n
            }
        };
        format!("((em_ref)&em_k{n})")
    }

    fn call(&mut self, cx: &mut Cx<'_>, dst: Option<VarId>, callee: &Callee, args: &[Operand]) {
        let f = cx.f;
        let a: Vec<String> = args.iter().map(|o| self.operand(o)).collect();
        match callee {
            Callee::Direct(g) => {
                let e = call(&self.fn_names[ix(*g)], &a);
                Self::assign(cx, dst, &e);
            }
            Callee::Indirect(c) => {
                let Type::Fn(fty) = self.core().ty(f.vars[*c].ty) else {
                    self.internal(format!(
                        "calling a value that is not a function in {}",
                        f.name
                    ));
                    return;
                };
                let ret = self.repr(fty.ret);
                let e = closure_call(&var(*c), ret, f, args, &a);
                Self::assign(cx, dst, &e);
            }
            Callee::Op {
                handler,
                effect,
                op,
            } => {
                let def = &self.core().effects[*effect].ops[*op];
                let ret = self.repr(def.ret);
                let h = var(*handler);
                let closure = format!("{h}->slots[{}].p", op + 1);
                cx.w.if_begin(&call("em_handler_ok", [&h]));
                if def.suspend {
                    // The implementation takes a resume function value last and returns
                    // nothing; the value to continue with comes from `em_perform_end`.
                    let name = names::string_literal(def.name.as_bytes());
                    let resume = call("em_resume_new", [h.as_str(), name.as_str(), repr_code(ret)]);
                    cx.w.decl("em_ref", "rs", Some(&resume));
                    let mut a = a.clone();
                    a.push("rs".to_owned());
                    let mut args = args.to_vec();
                    args.push(Operand::Const(Const::String(String::new())));
                    let call = closure_call(&closure, Repr::Void, f, &args, &a);
                    cx.w.stmt(&call);
                    cx.w.decl("em_word", "pw", Some("em_perform_end(rs)"));
                    if let Some(d) = dst {
                        cx.w.assign(&var(d), &format!("pw.{}", acc(ret)));
                    } else {
                        cx.w.stmt("(void)pw");
                    }
                } else {
                    let e = closure_call(&closure, ret, f, args, &a);
                    Self::assign(cx, dst, &e);
                }
                // A released handler takes none of the arguments: they are given up here.
                let given: Vec<String> = args
                    .iter()
                    .filter_map(|o| match o {
                        Operand::Var(v) if f.vars[*v].repr == Repr::Ref => Some(var(*v)),
                        _ => None,
                    })
                    .collect();
                if !given.is_empty() {
                    cx.w.else_begin();
                    for v in given {
                        cx.w.stmt(&call("em_drop", [v]));
                    }
                }
                cx.w.end();
            }
        }
    }

    fn builtin(&mut self, cx: &mut Cx<'_>, dst: Option<VarId>, op: Builtin, args: &[Operand]) {
        let f = cx.f;
        let a: Vec<String> = args.iter().map(|o| self.operand(o)).collect();
        let named = |name: &str| call(name, &a);
        let e = match op {
            Builtin::StringByteSize => named("em_string_byte_size"),
            Builtin::StringAppend => named("em_string_append"),
            Builtin::StringContains => named("em_string_contains"),
            Builtin::StringStartsWith => named("em_string_starts_with"),
            Builtin::StringEndsWith => named("em_string_ends_with"),
            Builtin::StringSplit => named("em_string_split"),
            Builtin::StringJoin => named("em_string_join"),
            Builtin::StringTrim => named("em_string_trim"),
            Builtin::StringCodePoints => named("em_string_code_points"),
            Builtin::StringFromCodePoint => named("em_string_from_code_point"),
            Builtin::IntToString => named("em_int_to_string"),
            Builtin::IntParse => named("em_int_parse"),
            Builtin::IntCheckedAdd => named("em_int_checked_add"),
            Builtin::IntBitAnd | Builtin::Int64BitAnd => format!("({} & {})", a[0], a[1]),
            Builtin::IntBitOr | Builtin::Int64BitOr => format!("({} | {})", a[0], a[1]),
            Builtin::IntBitXor | Builtin::Int64BitXor => format!("({} ^ {})", a[0], a[1]),
            Builtin::IntBitNot | Builtin::Int64BitNot => format!("(~{})", a[0]),
            Builtin::IntShiftLeft => named("em_ishl"),
            Builtin::IntShiftRight => named("em_ishr"),
            Builtin::IntShiftRightUnsigned => named("em_iushr"),
            Builtin::Int64FromInt => format!("(int64_t){}", a[0]),
            Builtin::Int64ToString => named("em_int64_to_string"),
            Builtin::Int64ToInt => format!("(int32_t)(uint32_t)(uint64_t){}", a[0]),
            Builtin::Int64ShiftLeft => named("em_lshl"),
            Builtin::Int64ShiftRight => named("em_lshr"),
            Builtin::Int64ShiftRightUnsigned => named("em_lushr"),
            Builtin::FloatToString => named("em_float_to_string"),
            Builtin::FloatFromInt => format!("(double){}", a[0]),
            Builtin::FloatParse => named("em_float_parse"),
            Builtin::FloatFloor => named("em_float_floor"),
            Builtin::FloatCeil => named("em_float_ceil"),
            Builtin::FloatRound => named("em_float_round"),
            Builtin::FloatTruncate => named("em_float_truncate"),
            Builtin::CellNew => {
                let Some(d) = dst else { return };
                let content = args
                    .first()
                    .map_or(Repr::Void, |o| Self::operand_repr(f, o));
                let w = match args.first() {
                    Some(o) => self.word(f, o),
                    None => "(em_word){.l = 0}".to_owned(),
                };
                let desc = if content == Repr::Ref {
                    "&em_desc_cell_ref"
                } else {
                    "&em_desc_cell_val"
                };
                cx.w.assign(&var(d), &call("em_alloc", [desc, "1"]));
                cx.w.assign(&format!("{}->slots[0]", var(d)), &w);
                if content == Repr::Ref {
                    cx.w.stmt(&call("em_dup", &a[..1]));
                }
                return;
            }
            Builtin::CellGet => {
                if let Some(d) = dst {
                    let r = f.vars[d].repr;
                    cx.w.assign(&var(d), &format!("{}->{}", a[0], slot(0, r)));
                    if r == Repr::Ref {
                        cx.w.stmt(&call("em_dup", [var(d)]));
                    }
                }
                return;
            }
            Builtin::CellSet => {
                let Some(v) = args.get(1) else { return };
                match Self::operand_repr(f, v) {
                    Repr::Ref => {
                        cx.w.stmt(&call("em_dup", &a[1..2]));
                        cx.w.block(|w| {
                            w.decl("em_ref", "old", Some(&format!("{}->slots[0].p", a[0])));
                            w.assign(&format!("{}->slots[0].p", a[0]), &a[1]);
                            w.stmt("em_drop(old)");
                        });
                    }
                    Repr::Void => {}
                    r => cx.w.assign(&format!("{}->{}", a[0], slot(0, r)), &a[1]),
                }
                return;
            }
            Builtin::StringLength
            | Builtin::StringChars
            | Builtin::Panic
            | Builtin::Todo
            | Builtin::AssertFail
            | Builtin::Dbg
            | Builtin::Inspect
            | Builtin::ShowNested
            | Builtin::ShowString
            | Builtin::DebugPrint => {
                self.internal(format!("builtin {op:?} left in {}", f.name));
                return;
            }
        };
        Self::assign(cx, dst, &e);
    }

    /// An external function: converts the arguments for C, calls the host function and converts
    /// the result back (spec 12.4). The arguments are borrowed.
    fn external(&mut self, out: &mut Writer, id: FnId, f: &Function, ext: &emela_core::External) {
        out.comment(&format!("external {}", f.name));
        let sig = self.signature(id, f, "");
        out.static_func(&sig, |w| self.external_body(w, f, ext));
    }

    fn external_body(&mut self, w: &mut Writer, f: &Function, ext: &emela_core::External) {
        let ret = self.repr(f.ret);
        let dummy = dummy(ret);
        let Some(binding) = ext.binding("c") else {
            let msg = format!(
                "external function `{}` is not available on this target",
                display_name(&f.name)
            );
            w.stmt(&call(
                "em_raise_cstr",
                [names::string_literal(msg.as_bytes())],
            ));
            w.ret(dummy);
            return;
        };
        let host = match &binding.host {
            HostRef::Global(name) => name.clone(),
            HostRef::Import { module, name } => {
                match module {
                    HostModule::Bundled(path) => {
                        if !self.bundled.contains(path) {
                            self.bundled.push(path.clone());
                        }
                    }
                    HostModule::File(path) => {
                        if !self.host_files.contains(path) {
                            self.host_files.push(path.clone());
                        }
                    }
                    HostModule::Named(_) => {}
                }
                name.clone()
            }
        };
        if !names::is_c_identifier(&host) {
            self.errors.push(CError::new(
                CErrorKind::Unsupported,
                format!(
                    "`{host}` in `@external(c, ...)` of `{}` is not a C function name",
                    f.name
                ),
            ));
        }
        let mut params = Vec::new();
        for &p in &f.params {
            match self.host_ty(f.vars[p].ty) {
                Some(t) => params.push((p, t)),
                None => {
                    self.host_type_error(f, f.vars[p].ty);
                    return;
                }
            }
        }
        let ret_ty = if f.ret == TypeId::UNIT || f.ret == TypeId::NEVER {
            HostTy::Unit
        } else {
            match self.host_ty(f.ret) {
                Some(t) => t,
                None => {
                    self.host_type_error(f, f.ret);
                    return;
                }
            }
        };
        if self.host_names.insert(host.clone()) {
            let mut ps: Vec<&str> = params.iter().map(|(_, t)| t.param()).collect();
            // A `suspend fn` takes the task last and completes it later (spec 12.6).
            if f.suspends {
                ps.push("em_task *");
            }
            let ret = if f.suspends { "void" } else { ret_ty.ret() };
            self.host_protos.extern_proto(&signature(ret, &host, ps));
        }
        let mut host_args = Vec::new();
        for (i, (p, t)) in params.iter().enumerate() {
            let v = var(*p);
            host_args.push(match t {
                HostTy::String => {
                    let c = format!("c{i}");
                    w.decl("const char *", &c, Some(&call("em_cstr", [&v])));
                    w.if_return(&format!("{c} == NULL"), dummy);
                    c
                }
                HostTy::Bool => format!("({v} != 0)"),
                HostTy::Handle => call("em_host_get", [&v]),
                _ => v,
            });
        }
        let name = names::string_literal(display_name(&f.name).as_bytes());
        if f.suspends {
            let kind = match ret_ty {
                HostTy::Unit => "EM_HOST_UNIT",
                HostTy::Int => "EM_HOST_INT",
                HostTy::Int64 => "EM_HOST_INT64",
                HostTy::Float => "EM_HOST_FLOAT",
                HostTy::Bool => "EM_HOST_BOOL",
                HostTy::String => "EM_HOST_STRING",
                HostTy::Handle => "EM_HOST_HANDLE",
            };
            w.decl(
                "em_task *",
                "task",
                Some(&call("em_task_new", [kind, name.as_str()])),
            );
            host_args.push("task".to_owned());
            w.stmt(&call(&host, &host_args));
            if ret == Repr::Void {
                w.stmt("em_task_end(task)");
            } else {
                w.ret(Some(&format!("em_task_end(task).{}", acc(ret))));
            }
            return;
        }
        let host_call = call(&host, &host_args);
        match ret_ty {
            HostTy::Unit => {
                w.stmt(&host_call);
                w.ret(dummy);
            }
            HostTy::String => {
                w.ret(Some(&call("em_from_host_string", [host_call, name])));
            }
            HostTy::Bool => w.ret(Some(&format!("{host_call} ? 1 : 0"))),
            HostTy::Handle => w.ret(Some(&call("em_host_box", [host_call]))),
            _ => w.ret(Some(&host_call)),
        }
    }

    fn host_ty(&self, ty: TypeId) -> Option<HostTy> {
        let core = self.core();
        Some(match core.ty(ty) {
            Type::Int => HostTy::Int,
            Type::Int64 => HostTy::Int64,
            Type::Float => HostTy::Float,
            Type::Bool => HostTy::Bool,
            Type::String => HostTy::String,
            Type::Unit | Type::Never => HostTy::Unit,
            Type::Enum(id, _) if core.enums[*id].external => HostTy::Handle,
            _ => return None,
        })
    }

    fn host_type_error(&mut self, f: &Function, ty: TypeId) {
        let name = emela_lir::core_ty(self.core(), ty);
        let (kind, what) = if matches!(self.core().ty(ty), Type::Fn(_)) {
            (
                CErrorKind::Callback,
                format!(
                    "external function `{}` takes a callback, which target `c` does not support yet",
                    f.name
                ),
            )
        } else {
            (
                CErrorKind::Unsupported,
                format!(
                    "external function `{}` uses the type {name}, which cannot cross to C",
                    f.name
                ),
            )
        };
        self.errors.push(CError::new(kind, what));
    }

    fn cleanup(&self, out: &mut Writer) {
        out.static_func("void em_cleanup(void)", |w| {
            for &c in &self.consts {
                w.stmt(&format!("em_const_release(&em_c{})", ix(c)));
            }
        });
        out.blank();
    }

    /// The function the run calls for the entry `id` (main or a test function, which take no
    /// arguments): it calls it and returns its value as a word. `em_run` runs it as the root
    /// fiber (spec 14.5) and drops the value.
    fn entry_thunk(&mut self, out: &mut Writer, id: FnId) -> (String, Repr) {
        let f = &self.m.functions[id];
        let name = self.fn_names[ix(id)].clone();
        if !f.params.is_empty() {
            self.internal(format!("the entry `{}` takes parameters", f.name));
        }
        let ret = self.repr(f.ret);
        let thunk = format!("{name}_entry");
        let no_args: [&str; 0] = [];
        out.static_func(&signature("em_word", &thunk, no_args), |w| {
            w.decl("em_word", "w", None);
            w.assign("w.l", "0");
            let entry = call(&name, no_args);
            if ret == Repr::Void {
                w.stmt(&entry);
            } else {
                w.assign(&format!("w.{}", acc(ret)), &entry);
            }
            w.ret(Some("w"));
        });
        out.blank();
        (thunk, ret)
    }

    /// The C functions of the exported fns (`[target.c.export]`): for each host name, a function
    /// with external linkage and the prototype of the table in `[ext.boundary]`. It stores its
    /// arguments in statics and runs a thunk as one launch; the thunk converts them, calls the fn
    /// and stores the converted value. A fn with a callback is not supported yet.
    fn c_exports(&mut self, out: &mut Writer, exports: &[(FnId, Vec<String>)]) {
        for (id, names) in exports {
            let f = &self.m.functions[*id];
            let fname = self.fn_names[ix(*id)].clone();
            let shown = display_name(&f.name).to_owned();
            let mut params = Vec::new();
            let mut ok = true;
            for &p in &f.params {
                match self.host_ty(f.vars[p].ty) {
                    Some(t) => params.push((p, t)),
                    None => {
                        self.export_type_error(&shown, f.vars[p].ty);
                        ok = false;
                    }
                }
            }
            let ret_ty = if f.ret == TypeId::UNIT || f.ret == TypeId::NEVER {
                Some(HostTy::Unit)
            } else {
                self.host_ty(f.ret)
            };
            let Some(ret_ty) = ret_ty else {
                self.export_type_error(&shown, f.ret);
                continue;
            };
            if !ok {
                continue;
            }
            let arg = |i: usize| format!("{fname}_xa{i}");
            let result = format!("{fname}_xr");
            for (i, (_, t)) in params.iter().enumerate() {
                if *t != HostTy::Unit {
                    let ty = if *t == HostTy::String {
                        "const char *"
                    } else {
                        t.param()
                    };
                    self.statics.decl(&format!("static {ty}"), &arg(i), None);
                }
            }
            if ret_ty != HostTy::Unit {
                self.statics
                    .decl(&format!("static {}", ret_ty.ret()), &result, None);
            }
            let thunk = format!("{fname}_xthunk");
            let name_lit = names::string_literal(shown.as_bytes());
            let ret = self.repr(f.ret);
            let no_args: [&str; 0] = [];
            out.static_func(&signature("em_word", &thunk, no_args), |w| {
                w.decl("em_word", "w", None);
                w.assign("w.l", "0");
                let mut args = Vec::new();
                let mut strings: Vec<String> = Vec::new();
                for (i, (p, t)) in params.iter().enumerate() {
                    let a = arg(i);
                    args.push(match t {
                        HostTy::String => {
                            let s = format!("s{i}");
                            w.decl(
                                "em_ref",
                                &s,
                                Some(&call(
                                    "em_from_export_string",
                                    [a.as_str(), name_lit.as_str()],
                                )),
                            );
                            w.if_begin(&format!("{s} == NULL"));
                            for earlier in &strings {
                                w.stmt(&call("em_drop", [earlier.as_str()]));
                            }
                            w.ret(Some("w"));
                            w.end();
                            strings.push(s.clone());
                            s
                        }
                        HostTy::Bool => format!("({a} ? 1 : 0)"),
                        HostTy::Handle => call("em_host_box", [&a]),
                        HostTy::Unit => dummy(self.m.functions[*id].vars[*p].repr)
                            .unwrap_or("0")
                            .to_owned(),
                        _ => a,
                    });
                }
                let value = call(&fname, &args);
                if ret == Repr::Void {
                    w.stmt(&value);
                    return w.ret(Some("w"));
                }
                w.decl(cty(ret), "r", Some(&value));
                w.if_return("em_defect != NULL", Some("w"));
                match ret_ty {
                    HostTy::Unit => {}
                    HostTy::String => w.assign(&result, &call("em_to_export_string", ["r"])),
                    HostTy::Bool => w.assign(&result, "(r != 0)"),
                    HostTy::Handle => {
                        w.assign(&result, &call("em_host_get", ["r"]));
                        w.stmt(&call("em_drop", ["r"]));
                    }
                    _ => w.assign(&result, "r"),
                }
                w.ret(Some("w"));
            });
            out.blank();
            for name in names {
                if !names::is_c_identifier(name) {
                    self.errors.push(CError::new(
                        CErrorKind::Unsupported,
                        format!(
                            "`{name}` in `@export(c, ...)` of `{shown}` is not a C function name"
                        ),
                    ));
                    continue;
                }
                let c_params: Vec<String> = params
                    .iter()
                    .enumerate()
                    .filter(|(_, (_, t))| *t != HostTy::Unit)
                    .map(|(i, (_, t))| param(t.param(), &format!("a{i}")))
                    .collect();
                let c_params = if c_params.is_empty() {
                    vec!["void".to_owned()]
                } else {
                    c_params
                };
                out.func(&signature(ret_ty.ret(), name, c_params), |w| {
                    w.stmt(&call("em_export_enter", [name_lit.as_str()]));
                    for (i, (_, t)) in params.iter().enumerate() {
                        if *t != HostTy::Unit {
                            w.assign(&arg(i), &format!("a{i}"));
                        }
                    }
                    w.stmt(&call("em_run", [thunk.as_str(), "EM_REPR_VOID"]));
                    w.stmt("em_export_leave()");
                    if ret_ty != HostTy::Unit {
                        w.ret(Some(&result));
                    }
                });
                out.blank();
            }
        }
    }

    fn export_type_error(&mut self, function: &str, ty: TypeId) {
        // Not E0427, which is about external functions: an exported fn with a callback has no
        // code of its own yet (the form of callbacks in C is open, 18.1 #38).
        let what = if matches!(self.core().ty(ty), Type::Fn(_)) {
            format!(
                "exported function `{function}` takes a callback, which target `c` does not support yet"
            )
        } else {
            let name = emela_lir::core_ty(self.core(), ty);
            format!("exported function `{function}` uses the type {name}, which cannot cross to C")
        };
        self.errors.push(CError::new(CErrorKind::Unsupported, what));
    }

    /// `int main(int argc, char **argv)`: starts the runtime, runs `body` and exits.
    fn main_func(out: &mut Writer, body: impl FnOnce(&mut Writer)) {
        let sig = signature("int", "main", ["int argc", "char **argv"]);
        out.func(&sig, |w| {
            w.stmt("em_start(argc, argv)");
            body(w);
            w.ret(Some("em_exit(em_cleanup)"));
        });
    }

    /// Runs the tests one by one and reports each result (the JS test runner's protocol).
    fn c_test_main(&mut self, out: &mut Writer, tests: &[(String, FnId)]) {
        self.cleanup(out);
        let thunks: Vec<(String, Repr)> = tests
            .iter()
            .map(|(_, id)| self.entry_thunk(out, *id))
            .collect();
        Self::main_func(out, |w| {
            for ((name, _), (thunk, ret)) in tests.iter().zip(thunks) {
                w.stmt(&call("em_run", [thunk.as_str(), repr_code(ret)]));
                w.stmt(&call(
                    "em_test_result",
                    [names::string_literal(name.as_bytes())],
                ));
            }
            w.stmt("em_test_done()");
        });
    }

    fn c_main(&mut self, out: &mut Writer, main: Option<FnId>) {
        self.cleanup(out);
        let thunk = main.map(|id| self.entry_thunk(out, id));
        Self::main_func(out, |w| {
            if let Some((thunk, ret)) = thunk {
                w.stmt(&call("em_run", [thunk.as_str(), repr_code(ret)]));
            }
        });
    }
}

/// The runtime's constant for a representation (`EM_REPR_I32`).
fn repr_code(r: Repr) -> &'static str {
    match r {
        Repr::I32 => "EM_REPR_I32",
        Repr::I64 => "EM_REPR_I64",
        Repr::F64 => "EM_REPR_F64",
        Repr::Ref => "EM_REPR_REF",
        Repr::Void => "EM_REPR_VOID",
    }
}

/// Calls the closure record `closure` with itself as the environment, then `args`.
fn closure_call(closure: &str, ret: Repr, f: &Function, args: &[Operand], a: &[String]) -> String {
    let mut params = vec!["em_ref".to_owned()];
    params.extend(
        args.iter()
            .map(|o| cty(Emitter::operand_repr(f, o)).to_owned()),
    );
    let mut call_args = vec![closure.to_owned()];
    call_args.extend(a.iter().cloned());
    format!(
        "(({} (*)({}))em_closure_fn({closure}))({})",
        cty(ret),
        params.join(", "),
        call_args.join(", ")
    )
}

fn prim(op: PrimOp, ty: PrimTy, a: &[String]) -> String {
    let bin = |sym: &str| format!("({} {sym} {})", a[0], a[1]);
    match ty {
        PrimTy::I32 | PrimTy::I64 => {
            let p = if ty == PrimTy::I32 { "em_i" } else { "em_l" };
            match op {
                PrimOp::Add => format!("{p}add({}, {})", a[0], a[1]),
                PrimOp::Sub => format!("{p}sub({}, {})", a[0], a[1]),
                PrimOp::Mul => format!("{p}mul({}, {})", a[0], a[1]),
                PrimOp::Div => format!("{p}div({}, {})", a[0], a[1]),
                PrimOp::Rem => format!("{p}rem({}, {})", a[0], a[1]),
                PrimOp::Neg => format!("{p}neg({})", a[0]),
                PrimOp::Not => format!("(!{})", a[0]),
                _ => bin(op.symbol()),
            }
        }
        PrimTy::F64 => match op {
            PrimOp::Rem => format!("em_fmod({}, {})", a[0], a[1]),
            PrimOp::Neg => format!("(-{})", a[0]),
            PrimOp::Not => format!("(!{})", a[0]),
            _ => bin(op.symbol()),
        },
        PrimTy::String => match op {
            PrimOp::Eq => format!("em_str_eq({}, {})", a[0], a[1]),
            PrimOp::Ne => format!("(!em_str_eq({}, {}))", a[0], a[1]),
            _ => format!("(em_str_cmp({}, {}) {} 0)", a[0], a[1], op.symbol()),
        },
    }
}
