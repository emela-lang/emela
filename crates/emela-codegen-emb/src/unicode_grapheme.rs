const INCB_LINKER: u32 = 3;

pub(crate) fn grapheme_count(value: &str) -> usize {
    let mut chars = value.chars();
    let Some(first) = chars.next() else {
        return 0;
    };

    let first = first as u32;
    let mut previous_property = grapheme_break_property(first);
    let mut incb_has_linker = indic_conjunct_break_property(first) == INCB_LINKER;
    let mut ep_extend_run = is_extended_pictographic(first);
    let mut zwj_after_ep = false;
    let mut regional_indicator_run = usize::from(previous_property == GCB_REGIONAL_INDICATOR);
    let mut count = 1;

    for current in chars {
        let current = current as u32;
        let current_property = grapheme_break_property(current);
        let current_incb = indic_conjunct_break_property(current);
        let current_is_ep = is_extended_pictographic(current);
        let previous_is_control = matches!(previous_property, GCB_CR | GCB_LF | GCB_CONTROL);
        let current_is_control = matches!(current_property, GCB_CR | GCB_LF | GCB_CONTROL);
        let no_break = (previous_property == GCB_CR && current_property == GCB_LF)
            || (!previous_is_control
                && !current_is_control
                && (previous_property == GCB_L
                    && matches!(current_property, GCB_L | GCB_V | GCB_LV | GCB_LVT)
                    || matches!(previous_property, GCB_LV | GCB_V)
                        && matches!(current_property, GCB_V | GCB_T)
                    || matches!(previous_property, GCB_LVT | GCB_T)
                        && current_property == GCB_T
                    || matches!(current_property, GCB_EXTEND | GCB_ZWJ)
                    || current_property == GCB_SPACING_MARK
                    || previous_property == GCB_PREPEND
                    // Unicode 18 revision 49 GB9c starts from an InCB Linker.
                    || current_incb == INCB_CONSONANT && incb_has_linker
                    || previous_property == GCB_ZWJ && zwj_after_ep && current_is_ep
                    || previous_property == GCB_REGIONAL_INDICATOR
                        && current_property == GCB_REGIONAL_INDICATOR
                        && regional_indicator_run % 2 == 1));
        let should_break = !no_break;

        if should_break {
            count += 1;
        }

        let current_zwj_after_ep = current_property == GCB_ZWJ && ep_extend_run;
        if current_is_ep {
            ep_extend_run = true;
        } else if current_property != GCB_EXTEND {
            ep_extend_run = false;
        }
        zwj_after_ep = current_zwj_after_ep;

        if current_incb == INCB_LINKER {
            incb_has_linker = true;
        } else if current_incb != INCB_EXTEND {
            incb_has_linker = false;
        }

        if current_property == GCB_REGIONAL_INDICATOR {
            if previous_property == GCB_REGIONAL_INDICATOR {
                regional_indicator_run += 1;
            } else {
                regional_indicator_run = 1;
            }
        } else {
            regional_indicator_run = 0;
        }
        previous_property = current_property;
    }

    count
}

fn grapheme_break_property(code_point: u32) -> u32 {
    if code_point < 0x80 {
        if code_point == 0x0d {
            return GCB_CR;
        }
        if code_point == 0x0a {
            return GCB_LF;
        }
        if code_point < 0x20 || code_point == 0x7f {
            return GCB_CONTROL;
        }
        return 0;
    }
    if (0xac00..=0xd7a3).contains(&code_point) {
        return if (code_point - 0xac00).is_multiple_of(28) {
            GCB_LV
        } else {
            GCB_LVT
        };
    }
    property_lookup(GRAPHEME_BREAK_RANGES, code_point)
}

fn indic_conjunct_break_property(code_point: u32) -> u32 {
    property_lookup(INDIC_CONJUNCT_BREAK_RANGES, code_point)
}

fn is_extended_pictographic(code_point: u32) -> bool {
    property_lookup(EXTENDED_PICTOGRAPHIC_RANGES, code_point) != 0
}

fn property_lookup(ranges: &[(u32, u32)], code_point: u32) -> u32 {
    let index = ranges.partition_point(|(start, _)| *start <= code_point);
    if index == 0 {
        return 0;
    }
    let (_, end_and_value) = ranges[index - 1];
    if code_point <= end_and_value >> 4 {
        end_and_value & 0x0f
    } else {
        0
    }
}

